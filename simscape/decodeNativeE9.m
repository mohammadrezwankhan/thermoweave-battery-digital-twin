function [raw, ledger] = decodeNativeE9(output, config)
%DECODENATIVEE9 Decode the fixed E9 model's [temperature, SOC, held zone temperature] log.
if ~ismember("nativeE9", string(who(output)))
    error("thermoweave:simscape:MissingNativeE9Log", ...
        "The declared native E9 model did not return nativeE9.");
end
log = output.get("nativeE9");
n = config.cell.count;
zones = config.controller.zoneCount;
if ~isa(log, "timeseries") || isempty(log.Time) || ...
        ~isequal(size(log.Data), [numel(log.Time), n+1+zones]) || ...
        any(~isfinite(log.Data), "all") || any(~isfinite(log.Time)) || ...
        any(diff(log.Time) < 0) || log.Time(1) ~= 0 || ...
        log.Time(end) ~= config.simulation.duration_s
    error("thermoweave:simscape:InvalidNativeE9Log", ...
        "Expected a complete, finite time series of native E9 channels.");
end
% Keep the post-transition value at duplicate solver times.
[t, rows] = unique(log.Time(:), "last");
temperature = log.Data(rows, 1:n);
soc = log.Data(rows, n+1);
held = log.Data(rows, n+2:end);
current = config.electrical.current_A;
heat = current^2 * config.electrical.R0_Ohm * (1 + ...
    config.electrical.alphaT_per_K * (temperature-config.electrical.temperatureReference_K) + ...
    config.electrical.alphaSOC * (1-soc));
boundary = config.boundary.conductance_W_per_K * ...
    (config.boundary.temperature_K-temperature);
command = min(1, max(0, config.controller.Kp_per_K * ...
    (held-config.controller.referenceTemperature_K-config.controller.deadband_K)));

period = config.controller.samplePeriod_s;
knots = (0:period:t(end))';
sampledCommand = interp1(t, command, knots(1:end-1), "previous");
generated = trapz(t, sum(heat, 2));
ambient = trapz(t, sum(boundary, 2));
cooling = -config.controller.qMax_W * sum(sampledCommand, "all") * period;
stored = config.cell.thermalCapacity_J_per_K * sum(temperature(end,:)-temperature(1,:));
net = generated + ambient + cooling;
residual = abs(stored-net) / max([abs(stored), sum(abs([generated, ambient, cooling])), 1e-9]);
ledger = struct("generatedHeat_J", generated, "ambientHeat_J", ambient, ...
    "coolantHeat_J", cooling, "externalHeat_J", 0, "netHeat_J", net, ...
    "storedEnergyChange_J", stored, "normalizedResidual", residual, ...
    "integrationRule", "trapezoidal-native-states-and-held-controller");

grid = (0:config.simulation.outputStep_s:t(end))';
gridCommand = interp1(t, command, grid, "previous");
raw = struct("time_s", grid, "temperature_K", interp1(t, temperature, grid), ...
    "soc", repmat(interp1(t, soc, grid), 1, n), "current_A", repmat(current, numel(grid), 1), ...
    "boundaryTemperature_K", repmat(config.boundary.temperature_K, numel(grid), n), ...
    "boundaryConductance_W_per_K", repmat(config.boundary.conductance_W_per_K, numel(grid), n), ...
    "zoneCommand", gridCommand, "heatGeneration_W", interp1(t, heat, grid), ...
    "coolingPowerProxy_W", config.controller.qMax_W * sum(gridCommand, 2), ...
    "energyResidualNormalized", residual);
end
